import os
import unittest
from unittest.mock import patch

from fastapi.testclient import TestClient

from app.agents.trip_planner_agent import MultiAgentTripPlanner
from app.api.main import app
from app.models.schemas import (
    Attraction,
    Budget,
    DayPlan,
    Location,
    Meal,
    TripPlan,
)


def trip_payload(days=3):
    return {
        "city": "厦门",
        "start_date": "2026-07-24",
        "end_date": "2026-07-26",
        "travel_days": days,
        "transportation": "公共交通",
        "accommodation": "经济型酒店",
        "preferences": ["自然风光", "休闲", "美食"],
        "free_text_input": "希望安排轻松一点",
    }


class TripFastModeTests(unittest.TestCase):
    def setUp(self):
        self.client = TestClient(app)

    def test_trip_health_fast_mode_does_not_initialize_llm(self):
        def fail_if_called():
            raise AssertionError("LLM agent should not be initialized in fast mode")

        with patch.dict(os.environ, {"TRIP_FAST_MODE": "true"}), patch(
            "app.api.routes.trip.get_trip_planner_agent",
            fail_if_called,
        ):
            response = self.client.get("/api/trip/health")

        self.assertEqual(response.status_code, 200)
        body = response.json()
        self.assertEqual(body["status"], "healthy")
        self.assertEqual(body["mode"], "fast")
        self.assertFalse(body["llm_enabled"])

    def test_plan_trip_fast_mode_returns_curated_real_city_spots(self):
        def no_network_search(self, city, keyword):
            return []

        def no_weather(self, city):
            return {}

        with patch.dict(os.environ, {"TRIP_FAST_MODE": "true"}), patch.object(
            MultiAgentTripPlanner,
            "_amap_search_keyword",
            no_network_search,
        ), patch.object(
            MultiAgentTripPlanner,
            "_amap_weather",
            no_weather,
        ):
            response = self.client.post("/api/trip/plan", json=trip_payload(days=3))

        self.assertEqual(response.status_code, 200)
        body = response.json()
        self.assertTrue(body["success"])

        plan = body["data"]
        self.assertEqual(plan["city"], "厦门")
        self.assertEqual(len(plan["days"]), 3)
        self.assertGreater(plan["budget"]["total"], 0)
        self.assertEqual(plan["weather_info"], [])

        first_day = plan["days"][0]
        first_names = [spot["name"] for spot in first_day["attractions"]]
        self.assertIn("鼓浪屿", first_names)
        self.assertNotIn("厦门景点1", first_names)

        first_spot = first_day["attractions"][0]
        self.assertEqual(first_spot["location"]["longitude"], 118.067786)
        self.assertEqual(first_spot["location"]["latitude"], 24.444651)
        self.assertEqual(len(first_day["meals"]), 3)
        self.assertEqual(first_day["hotel"]["name"], "全季酒店(厦门中山路店)")
        self.assertGreater(first_day["hotel"]["estimated_cost"], 0)

        meal_names = [meal["name"] for meal in first_day["meals"]]
        self.assertIn("黄则和花生汤店(中山路店)", meal_names)
        self.assertIn("八婆婆烧仙草(轮渡店)", meal_names)
        self.assertIn("临家闽南菜(环岛路店)", meal_names)
        self.assertTrue(all(meal["address"] for meal in first_day["meals"]))
        self.assertTrue(all(meal["estimated_cost"] > 0 for meal in first_day["meals"]))

        route_segments = first_day["route_segments"]
        self.assertEqual(len(route_segments), len(first_day["attractions"]) - 1)
        self.assertEqual(route_segments[0]["from_name"], "鼓浪屿")
        self.assertEqual(route_segments[0]["to_name"], "厦门大学")
        self.assertGreater(route_segments[0]["distance_km"], 0)
        self.assertGreater(route_segments[0]["duration_minutes"], 0)

    def test_plan_trip_llm_mode_dispatches_to_agent(self):
        expected_plan = TripPlan(
            city="厦门",
            start_date="2026-07-24",
            end_date="2026-07-24",
            days=[
                DayPlan(
                    date="2026-07-24",
                    day_index=0,
                    description="LLM generated day",
                    transportation="公共交通",
                    accommodation="经济型酒店",
                    attractions=[
                        Attraction(
                            name="测试景点",
                            address="厦门市",
                            location=Location(longitude=118.1, latitude=24.4),
                            visit_duration=120,
                            description="Generated by fake LLM agent",
                        )
                    ],
                    meals=[
                        Meal(type="breakfast", name="早餐"),
                        Meal(type="lunch", name="午餐"),
                        Meal(type="dinner", name="晚餐"),
                    ],
                )
            ],
            weather_info=[],
            overall_suggestions="Use LLM mode",
            budget=Budget(
                total_attractions=0,
                total_hotels=300,
                total_meals=165,
                total_transportation=60,
                total=525,
            ),
        )

        class FakeAgent:
            def plan_trip(self, request):
                self.request_city = request.city
                return expected_plan

        with patch.dict(os.environ, {"TRIP_FAST_MODE": "false"}), patch(
            "app.api.routes.trip.get_trip_planner_agent",
            lambda: FakeAgent(),
        ):
            response = self.client.post("/api/trip/plan", json=trip_payload(days=1))

        self.assertEqual(response.status_code, 200)
        body = response.json()
        self.assertTrue(body["success"])
        self.assertEqual(body["data"]["overall_suggestions"], "Use LLM mode")
        self.assertEqual(body["data"]["days"][0]["attractions"][0]["name"], "测试景点")


if __name__ == "__main__":
    unittest.main()
